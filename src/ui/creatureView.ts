import Phaser from 'phaser';
import type { Selection } from '../core/stats';
import anchorData from '../data/anchors.json';

type Pt = [number, number];
interface AnchorData {
  rig: { hipOverlap: number; neckOverlap: number };
  anchors: Record<
    string,
    {
      head: { neck: Pt };
      torso: { neck: Pt; hip: Pt; shoulder: Pt };
      arms: { shoulder: Pt; tip: Pt };
      legs: { hip: Pt; ground: Pt };
    }
  >;
}
const DATA = anchorData as unknown as AnchorData;
const donorAnchors = (id: string) => DATA.anchors[id] ?? DATA.anchors.armadura;

/**
 * Builds a creature out of 4 atlas frames, assembled with the joint anchors in src/data/anchors.json
 * (generated by scripts/build-assets.mjs). Local origin (0,0) = feet centre; y grows downward.
 * Layers, back to front: legs, torso, head, front arm.
 */
export class CreatureView extends Phaser.GameObjects.Container {
  private legs: Phaser.GameObjects.Image;
  private torso: Phaser.GameObjects.Image;
  private head: Phaser.GameObjects.Image;
  private arm: Phaser.GameObjects.Image;
  private pieces: Phaser.GameObjects.Image[];
  private base: number;
  private facing: 1 | -1 = 1;

  constructor(scene: Phaser.Scene, x: number, y: number, sel: Selection, scale = 0.3) {
    super(scene, x, y);
    this.base = scale;
    const frame = (slot: string, donor: string) => `part_${donor}_${slot}`;
    const { hipOverlap, neckOverlap } = DATA.rig;
    const aL = donorAnchors(sel.legs).legs;
    const aT = donorAnchors(sel.torso).torso;
    const aH = donorAnchors(sel.head).head;
    const aA = donorAnchors(sel.arms).arms;

    // Legs: feet centre at (0,0); the hip point is where the torso plugs in.
    const hip: Pt = [0, aL.hip[1] - aL.ground[1]];
    this.legs = scene.add.image(-aL.hip[0], -aL.ground[1], 'atlas', frame('legs', sel.legs)).setOrigin(0, 0);
    // Torso: its hip sits on the legs' hip, sunk by hipOverlap so the outlines hide the seam.
    const torsoPos: Pt = [hip[0] - aT.hip[0], hip[1] + hipOverlap - aT.hip[1]];
    this.torso = scene.add
      .image(torsoPos[0], torsoPos[1], 'atlas', frame('torso', sel.torso))
      .setOrigin(0, 0);
    // Head: its neck sits on the torso's neck, sunk by neckOverlap.
    const neck: Pt = [torsoPos[0] + aT.neck[0], torsoPos[1] + aT.neck[1]];
    this.head = scene.add
      .image(neck[0] - aH.neck[0], neck[1] + neckOverlap - aH.neck[1], 'atlas', frame('head', sel.head))
      .setOrigin(0, 0);
    // Front arm pivots on the torso's shoulder point; its own shoulder anchor is the rotation origin.
    const shoulder: Pt = [torsoPos[0] + aT.shoulder[0], torsoPos[1] + aT.shoulder[1]];
    this.arm = scene.add.image(shoulder[0], shoulder[1], 'atlas', frame('arms', sel.arms));
    this.arm.setOrigin(aA.shoulder[0] / this.arm.width, aA.shoulder[1] / this.arm.height);
    this.pieces = [this.legs, this.torso, this.head, this.arm];
    this.add(this.pieces);
    this.setScale(scale);
    this.setAim(1, -12);
    scene.add.existing(this);
  }

  /** facing: 1 right, −1 left. angleDeg: absolute aim angle (0 = right, 90 = up, 180 = left). */
  setAim(facing: 1 | -1, angleDeg: number): void {
    this.facing = facing;
    this.setScale(this.base * facing, this.base);
    const rad = (angleDeg * Math.PI) / 180;
    // In local (unflipped) space the arm points right at rotation 0.
    this.arm.setRotation(facing > 0 ? -rad : -(Math.PI - rad));
  }

  /** Gentle idle bob so creatures feel alive. */
  idle(scene: Phaser.Scene, phase = 0): void {
    scene.tweens.add({
      targets: this.torso,
      scaleY: 1.03,
      duration: 900 + phase * 120,
      yoyo: true,
      repeat: -1,
      ease: 'Sine.easeInOut',
    });
    scene.tweens.add({
      targets: this.head,
      y: this.head.y - 4,
      duration: 900 + phase * 120,
      yoyo: true,
      repeat: -1,
      ease: 'Sine.easeInOut',
    });
  }

  flash(color = 0xffffff): void {
    this.pieces.forEach((i) => i.setTintFill(color));
    this.scene.time.delayedCall(90, () => this.pieces.forEach((i) => i.clearTint()));
  }

  /** Silhouette mode (used by the "pass the device" screen so nobody peeks). */
  setSilhouette(on: boolean, color = 0x4a4466): void {
    this.pieces.forEach((i) => (on ? i.setTintFill(color) : i.clearTint()));
  }

  private grayed = false;
  setGrayed(on: boolean): void {
    this.grayed = on;
    this.pieces.forEach((i) => (on ? i.setTint(0x555566) : i.clearTint()));
  }

  private iced = false;
  setIce(on: boolean): void {
    if (on === this.iced) return;
    this.iced = on;
    this.pieces.forEach((i) =>
      on ? i.setTint(0x9fd8ff) : this.grayed ? i.setTint(0x555566) : i.clearTint(),
    );
  }

  get facingDir(): 1 | -1 {
    return this.facing;
  }
}
